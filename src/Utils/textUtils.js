/**
 * Утилита для подсчета количества слов в тексте.
 * Принцип DRY: функция изолирована и может использоваться в любом компоненте.
 */
export const countWords = (text) => {
    if (!text || typeof text !== 'string') return 0;

    // Удаляем лишние пробелы по краям и разбиваем строку по пробелам/переносам
    const words = text.trim().split(/\s+/);

    // Если строка пустая, split вернет массив с одним пустым элементом, это нужно учесть
    return words[0] === "" ? 0 : words.length;
};
